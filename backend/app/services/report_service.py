def dataset_to_csv(df: pd.DataFrame) -> bytes:
    buffer = io.StringIO()
    df.to_csv(buffer, index=False)
    return buffer.getvalue().encode("utf-8")


def analysis_summary_to_csv(summary: Dict[str, Any]) -> bytes:
    rows: List[Dict[str, Any]] = []

    totals = summary.get("kpi", {}).get("totals") or {}
    for key, value in totals.items():
        rows.append({"section": "totals", "key": key, "value": to_python(value)})

    averages = summary.get("kpi", {}).get("averages") or {}
    for key, value in averages.items():
        rows.append({"section": "averages", "key": key, "value": to_python(value)})

    for key, value in (summary.get("profile", {}) or {}).items():
        if isinstance(value, (int, float, str)):
            rows.append({"section": "profile", "key": key, "value": to_python(value)})

    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=["section", "key", "value"])
    writer.writeheader()
    for row in rows:
        writer.writerow(row)
    return buffer.getvalue().encode("utf-8")


def scenario_report_to_csv(scenarios: List[Dict[str, Any]]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["scenario_name", "metric", "value"])
    for scenario in scenarios:
        name = scenario.get("name", "")
        totals = (scenario.get("results") or {}).get("scenario") or {}
        for key, value in totals.items():
            writer.writerow([name, key, to_python(value)])
    return buffer.getvalue().encode("utf-8")


