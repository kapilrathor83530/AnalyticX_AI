from io import BytesIO
from typing import Any, Dict, List


def build_pdf_report(metadata: Dict[str, Any], sections: List[Dict[str, Any]]) -> bytes:
    """Build a simple PDF report. Uses reportlab; not a full template engine."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    from reportlab.lib import colors

    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm)
    styles = getSampleStyleSheet()
    story: List[Any] = []

    story.append(Paragraph(metadata.get("dataset", "Analyticx AI Report"), styles["Title"]))
    story.append(Spacer(1, 12))
    story.append(Paragraph(f"Generated at: {metadata.get('generated_at', '')}", styles["Normal"]))
    story.append(Paragraph(f"Generator: {metadata.get('generator', 'Analyticx AI')}", styles["Normal"]))
    story.append(Spacer(1, 18))

    for section in sections:
        title = section.get("title", "")
        rows = section.get("rows", [])
        story.append(Paragraph(title, styles["Heading2"]))
        story.append(Spacer(1, 6))

        if not rows:
            story.append(Paragraph("No data", styles["Italic"]))
            story.append(Spacer(1, 12))
            continue

        table_data = [list(rows[0].keys())] + [[str(v) for v in row.values()] for row in rows]
        table = Table(table_data, hAlign="LEFT")
        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#94a3b8")),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                ]
            )
        )
        story.append(table)
        story.append(Spacer(1, 16))

    doc.build(story)
    return buffer.getvalue()


def build_pptx_report(
    metadata: dict,
    sections: List[dict],
    recommendations: List[str] | None = None,
) -> bytes:
    """Builds an executive PowerPoint presentation deck (.pptx) with Analyticx AI branding."""
    from io import BytesIO
    from pptx import Presentation

    prs = Presentation()

    # Slide 1: Title Slide
    title_slide = prs.slides.add_slide(prs.slide_layouts[0])
    title = title_slide.shapes.title
    subtitle = title_slide.placeholders[1]
    title.text = metadata.get("dataset", "Analyticx AI Executive Intelligence Deck")
    subtitle.text = (
        f"Automated Executive Management Report\n"
        f"Generated by Analyticx AI · {metadata.get('generated_at', '')}\n"
        f"Confidential · Decision Support System"
    )

    # Slide 2: Executive Summary & Scope
    summary_slide = prs.slides.add_slide(prs.slide_layouts[1])
    summary_slide.shapes.title.text = "Executive Summary & Data Scope"
    tf = summary_slide.placeholders[1].text_frame
    tf.text = f"Dataset: {metadata.get('dataset', 'Active Dataset')}"
    p = tf.add_paragraph()
    p.text = "Analytics Engine: Python Deterministic Grounding & Multi-Agent Inference"
    p = tf.add_paragraph()
    p.text = f"Report Date: {metadata.get('generated_at', '')}"

    # Slide 3: Detailed Findings & Section Breakdown
    for sec in sections[:4]:
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = sec.get("title", "Analysis Findings")
        body = slide.placeholders[1].text_frame
        rows = sec.get("rows", [])
        if rows:
            for r in rows[:6]:
                p = body.add_paragraph()
                p.text = " · ".join([f"{k}: {v}" for k, v in r.items()][:3])
        else:
            body.text = sec.get("text", "Automated section insights derived from primary dataset.")

    # Slide 4: Strategic Recommendations & Action Plan
    recs = recommendations or [
        "Audit top variance detractors and recalibrate operational pricing.",
        "Scale inventory and marketing in highest contributing growth regions.",
        "Establish automated recurring telemetry alerts for margin anomalies.",
    ]
    rec_slide = prs.slides.add_slide(prs.slide_layouts[1])
    rec_slide.shapes.title.text = "Strategic Recommendations & Next Steps"
    rec_body = rec_slide.placeholders[1].text_frame
    rec_body.text = "Key Data-Backed Business Actions:"
    for item in recs:
        p = rec_body.add_paragraph()
        p.text = f"• {item}"

    buffer = BytesIO()
    prs.save(buffer)
    return buffer.getvalue()

import base64
from typing import List


def build_pdf_report_with_charts(
    metadata: dict,
    sections: List[dict],
    charts: List[dict] | None = None,
) -> bytes:
    """charts: list of {"title": str, "image_base64": str (data URI or raw b64)}"""
    from io import BytesIO

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import (
        Image, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
    )

    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm)
    styles = getSampleStyleSheet()
    story: List[object] = []

    story.append(Paragraph(metadata.get("dataset", "Analyticx AI Report"), styles["Title"]))
    story.append(Spacer(1, 8))
    story.append(Paragraph(f"Generated: {metadata.get('generated_at', '')}", styles["Normal"]))
    story.append(Spacer(1, 18))

    for section in sections:
        story.append(Paragraph(section.get("title", ""), styles["Heading2"]))
        rows = section.get("rows", [])
        if rows:
            table_data = [list(rows[0].keys())] + [[str(v) for v in r.values()] for r in rows]
            table = Table(table_data, hAlign="LEFT")
            table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#94a3b8")),
                        ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ]
                )
            )
            story.append(table)
        else:
            story.append(Paragraph("No data", styles["Italic"]))
        story.append(Spacer(1, 16))

    if charts:
        story.append(PageBreak())
        for chart in charts:
            story.append(Paragraph(chart.get("title", "Chart"), styles["Heading3"]))
            b64 = chart.get("image_base64", "")
            if b64.startswith("data:"):
                b64 = b64.split(",", 1)[-1]
            try:
                raw = base64.b64decode(b64)
                img = Image(BytesIO(raw), width=16 * cm, height=10 * cm)
                story.append(img)
                story.append(Spacer(1, 16))
            except Exception:
                story.append(Paragraph("Chart could not be embedded.", styles["Italic"]))

    doc.build(story)
    return buffer.getvalue()


def build_docx_report(
    metadata: dict,
    sections: List[dict],
    recommendations: List[str] | None = None,
) -> bytes:
    """Builds an executive Word document (.docx) with Analyticx AI branding."""
    from io import BytesIO
    from docx import Document
    from docx.shared import Pt, RGBColor

    doc = Document()

    # Document Header Title
    title_p = doc.add_paragraph()
    title_run = title_p.add_run(metadata.get("dataset", "Analyticx AI Executive Business Report"))
    title_run.font.size = Pt(22)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(14, 116, 144)

    sub_p = doc.add_paragraph()
    sub_run = sub_p.add_run(f"Automated Executive Management Briefing · Generated: {metadata.get('generated_at', '')}")
    sub_run.font.size = Pt(10)
    sub_run.font.italic = True

    doc.add_paragraph()

    # Section 1: Executive Scope
    doc.add_heading("1. Executive Summary & Context", level=1)
    doc.add_paragraph(
        f"This document represents the official verified business intelligence briefing for dataset "
        f"'{metadata.get('dataset', 'Active Dataset')}'. All statistical findings and root-cause driver "
        f"decompositions are computed using deterministic Python analytics tools."
    )

    # Detailed Sections & Tables
    sec_idx = 2
    for sec in sections:
        sec_title = sec.get("title", f"Section {sec_idx}")
        doc.add_heading(f"{sec_idx}. {sec_title}", level=1)
        sec_idx += 1

        sec_text = sec.get("text")
        if sec_text:
            doc.add_paragraph(sec_text)

        rows = sec.get("rows", [])
        if rows:
            cols = list(rows[0].keys())
            table = doc.add_table(rows=len(rows) + 1, cols=len(cols))
            table.style = "Table Grid"

            hdr_cells = table.rows[0].cells
            for i, col in enumerate(cols):
                hdr_cells[i].text = col
                for run in hdr_cells[i].paragraphs[0].runs:
                    run.font.bold = True
                    run.font.size = Pt(9)

            for r_idx, row_dict in enumerate(rows):
                row_cells = table.rows[r_idx + 1].cells
                for c_idx, col in enumerate(cols):
                    row_cells[c_idx].text = str(row_dict.get(col, ""))
                    for run in row_cells[c_idx].paragraphs[0].runs:
                        run.font.size = Pt(9)

            doc.add_paragraph()

    # Strategic Recommendations Section
    recs = recommendations or [
        "Audit top variance detractors and recalibrate operational pricing.",
        "Scale inventory and marketing in highest contributing growth regions.",
        "Establish automated recurring telemetry alerts for margin anomalies.",
    ]
    doc.add_heading(f"{sec_idx}. Strategic Recommendations & Action Items", level=1)
    for rec in recs:
        p_rec = doc.add_paragraph(style="List Bullet")
        r_run = p_rec.add_run(rec)
        r_run.font.size = Pt(10)

    doc.add_paragraph()
    footer_p = doc.add_paragraph()
    footer_run = footer_p.add_run("Analyticx AI Platform · Enterprise Decision Support System · Confidential")
    footer_run.font.size = Pt(9)
    footer_run.font.color.rgb = RGBColor(148, 163, 184)

    buffer = BytesIO()
    doc.save(buffer)
    return buffer.getvalue()
